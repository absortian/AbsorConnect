const { app, BrowserWindow } = require('electron')
const fs = require('node:fs')
const path = require('node:path')
const assert = require('node:assert/strict')
const output = process.argv.find(a => a.startsWith('--output='))?.slice(9)
if (!output) process.exit(64)
app.setPath('userData', path.join(output, 'profile'))
app.commandLine.appendSwitch('autoplay-policy', 'no-user-gesture-required')
app.whenReady().then(async () => {
  const w = new BrowserWindow({ width: 1100, height: 800, show: false, webPreferences: { sandbox: true, contextIsolation: true, nodeIntegration: false, backgroundThrottling: false } })
  const js = code => w.webContents.executeJavaScript(code)
  const snapshot = name => w.webContents.capturePage().then(p => fs.writeFileSync(path.join(output, name+'.png'), p.toPNG()))
  try {
    await w.loadFile(path.join(output, 'index.html'))
    await js('contextLab.connect()')
    const desktop = await js('contextLab.state()')
    assert.equal(desktop.enableCount, 1)
    assert.equal(desktop.videoHidden, false)
    assert.equal(desktop.filesHidden, false)
    await snapshot('desktop')
    await js('contextLab.context("transition", false)')
    await js('contextLab.ready(() => contextLab.state().videoHidden)')
    const transition = await js('contextLab.state()')
    assert.equal(transition.clipboardWatch, false)
    assert.equal(transition.filesHidden, true)
    assert.equal(transition.soundHidden, true)
    assert.equal(transition.shortcutsDisabled, true)
    await snapshot('transition')
    await js('contextLab.context("login", true)')
    await js('contextLab.ready(() => !contextLab.state().videoHidden)')
    const login = await js('contextLab.state()')
    assert.equal(login.filesHidden, true)
    assert.equal(login.clipboardWatch, false)
    assert.equal(login.shortcutsDisabled, false)
    await snapshot('login')
    await js('contextLab.context("user_desktop", true, 1); contextLab.features()')
    await new Promise(r => setTimeout(r, 100))
    assert.equal((await js('contextLab.state()')).state, login.state)
    await js('contextLab.context("user_desktop", true)')
    await js('contextLab.ready(() => !contextLab.state().videoHidden)')
    const returned = await js('contextLab.state()')
    assert.equal(returned.filesHidden, true)
    assert.equal(returned.clipboardWatch, false)
    fs.writeFileSync(path.join(output, 'report.json'), JSON.stringify({ ok: true, productionViewerUsed: true, realLocalWebRtc: true, syntheticVideoOnly: true, desktop, transition, login, returned, physicalHostTested: false, protectedScreenCaptured: false }, null, 2), {mode:0o600})
    console.log(JSON.stringify({ok:true, productionViewerUsed:true, realLocalWebRtc:true}))
  } catch (error) {
    console.error(error.message)
    fs.writeFileSync(path.join(output, 'failure.json'), JSON.stringify({error:error.message}), {mode:0o600})
    process.exitCode = 1
  } finally {
    await js('contextLab.close()').catch(() => {})
    w.destroy()
    app.quit()
  }
})
setTimeout(() => { process.exitCode = 1; app.quit() }, 45000).unref()
