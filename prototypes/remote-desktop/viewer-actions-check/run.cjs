const fs = require('node:fs')
const path = require('node:path')
const { spawnSync } = require('node:child_process')
const { buildSync } = require('esbuild')
const root = path.resolve(__dirname, '../../..')
const lab = path.resolve(process.argv[2] || '')
const info = fs.lstatSync(lab)
if (!info.isDirectory() || info.isSymbolicLink() || info.uid !== process.getuid() || info.mode & 0o077) throw new Error('Se requiere laboratorio propio privado')
const output = fs.mkdtempSync(path.join(lab, 'viewer-actions-'))
fs.chmodSync(output, 0o700)
for (const [entry, file] of [['src/renderer/viewer/main.ts','viewer.js'],['prototypes/remote-desktop/viewer-actions-check/fixture.ts','fixture.js']])
  buildSync({absWorkingDir:root, entryPoints:[entry], outfile:path.join(output,file), bundle:true, platform:'browser', format:'iife', target:'chrome142'})
const html = fs.readFileSync(path.join(root,'src/renderer/viewer.html'),'utf8')
  .replace('</head>', '<link rel="stylesheet" href="viewer.css" /></head>')
  .replace('<script type="module" src="/viewer/main.ts"></script>', '<script src="fixture.js"></script><script src="viewer.js"></script>')
fs.writeFileSync(path.join(output,'index.html'),html)
const run = spawnSync(require('electron'), [path.join(__dirname,'main.cjs'),'--output='+output], {cwd:root,stdio:'inherit',timeout:110000})
console.log('Informe local: '+path.join(output,'report.json'))
const reportPath = path.join(output, 'report.json')
const valid = fs.existsSync(reportPath) && JSON.parse(fs.readFileSync(reportPath, 'utf8')).ok === true
process.exit(run.status === 0 && valid ? 0 : 1)
